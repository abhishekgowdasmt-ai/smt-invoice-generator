@app.route('/api/admin/trips/optimize', methods=['POST'])
def optimize_trips():
    if not check_admin_auth():
        return jsonify({"error": "Unauthorized Access"}), 401
        
    conn = get_db_connection()
    cursor = conn.cursor()
    
    # Fetch all Pending inquiries
    cursor.execute('SELECT * FROM inquiries WHERE status = "Pending"')
    inquiries = cursor.fetchall()
    
    if not inquiries:
        conn.close()
        return jsonify({"message": "No pending inquiries to optimize. Submit a booking quote from client homepage first."}), 200
        
    # Fetch available Active cabs
    cursor.execute('SELECT * FROM cabs WHERE status = "Active"')
    cabs = cursor.fetchall()
    
    # Fetch active drivers
    cursor.execute('SELECT * FROM drivers WHERE status = "Active"')
    drivers = cursor.fetchall()
    
    if not cabs or not drivers:
        conn.close()
        return jsonify({"error": "Active cabs and drivers are required for routing. Please ensure cabs and drivers are registered and set to Active."}), 400
        
    # Fetch companies
    cursor.execute('SELECT * FROM companies')
    companies = cursor.fetchall()
    company_map = {c["name"].lower(): c["id"] for c in companies}
    default_company_id = companies[0]["id"] if companies else 1
    
    # Simple clustering: group inquiries by service type & company
    clusters = {}
    for inq in inquiries:
        comp_name = inq["company"] or ""
        key = (inq["service_type"], comp_name)
        if key not in clusters:
            clusters[key] = []
        clusters[key].append(inq)
        
    created_count = 0
    import random
    
    cab_idx = 0
    drv_idx = 0
    
    for key, cluster_inqs in clusters.items():
        if cab_idx >= len(cabs) or drv_idx >= len(drivers):
            cab_idx = cab_idx % len(cabs)
            drv_idx = drv_idx % len(drivers)
            
        cab = cabs[cab_idx]
        driver = drivers[drv_idx]
        cab_idx += 1
        drv_idx += 1
        
        service_type, company_name = key
        
        company_id = default_company_id
        if company_name:
            for cname, cid in company_map.items():
                if company_name.lower() in cname or cname in company_name.lower():
                    company_id = cid
                    break
                    
        route_name = f"SMT HQ ➡️ {company_name or service_type}"
        created_at = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
        
        # Simple ETA in future (e.g. +45 mins)
        eta = "18:45"
        
        cursor.execute('''
            INSERT INTO trips (cab_id, driver_id, company_id, route_name, status, progress, speed, eta, created_at)
            VALUES (?, ?, ?, ?, 'Scheduled', 0.0, 0, ?, ?)
        ''', (cab["id"], driver["id"], company_id, route_name, eta, created_at))
        trip_id = cursor.lastrowid
        
        # Insert passengers
        for inq in cluster_inqs:
            cursor.execute('UPDATE inquiries SET status = "In Progress" WHERE id = ?', (inq["id"],))
            cursor.execute('''
                INSERT INTO trip_passengers (trip_id, name, stop_name, status)
                VALUES (?, ?, ?, 'Pending')
            ''', (trip_id, inq["name"], inq["details"] or "Tech Park Gate"))
            
        created_count += 1
        
    conn.commit()
    conn.close()
    return jsonify({"message": f"Optimization complete. Created {created_count} active trips routes.", "trips_created": created_count})


@app.route('/api/admin/trips/simulate-tick', methods=['POST'])
def simulate_tick():
    if not check_admin_auth():
        return jsonify({"error": "Unauthorized Access"}), 401
        
    conn = get_db_connection()
    cursor = conn.cursor()
    
    # Fetch all active trips
    cursor.execute('SELECT * FROM trips WHERE status IN ("Scheduled", "En Route", "SOS Alert")')
    trips = cursor.fetchall()
    
    import random
    tick_time = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    alerts_added = 0
    
    for trip in trips:
        curr_progress = trip["progress"]
        curr_status = trip["status"]
        
        if curr_progress >= 100.0:
            cursor.execute('UPDATE trips SET status = "Completed", speed = 0, progress = 100.0 WHERE id = ?', (trip["id"],))
            cursor.execute('UPDATE trip_passengers SET status = "Dropped" WHERE trip_id = ?', (trip["id"],))
            continue
            
        new_progress = curr_progress + random.uniform(8.0, 18.0)
        if new_progress >= 100.0:
            new_progress = 100.0
            new_status = 'Completed'
            new_speed = 0
        else:
            new_status = 'En Route' if curr_status == 'Scheduled' else curr_status
            new_speed = random.randint(35, 75)
            
        cursor.execute('UPDATE trips SET progress = ?, status = ?, speed = ? WHERE id = ?', 
                       (new_progress, new_status, new_speed, trip["id"]))
        
        # EV Cab depletion logic
        cursor.execute('SELECT is_ev, charge_status, range_km FROM cabs WHERE id = ?', (trip["cab_id"],))
        cab = cursor.fetchone()
        if cab and cab["is_ev"] == 1:
            curr_soc = cab["charge_status"] if cab["charge_status"] is not None else 80
            curr_range = cab["range_km"] if cab["range_km"] is not None else 180
            new_soc = max(0, curr_soc - random.randint(2, 6))
            new_range = max(0, curr_range - random.randint(5, 15))
            cursor.execute('UPDATE cabs SET charge_status = ?, range_km = ? WHERE id = ?', (new_soc, new_range, trip["cab_id"]))
            
        # Passenger checks
        if new_progress >= 90.0:
            cursor.execute('UPDATE trip_passengers SET status = "Dropped" WHERE trip_id = ?', (trip["id"],))
        elif new_progress >= 30.0:
            cursor.execute('UPDATE trip_passengers SET status = "Onboard" WHERE trip_id = ? AND status = "Pending"', (trip["id"],))
            
        # Telemetry speeding/geofence alerts (8% chance)
        if new_status != 'Completed' and random.random() < 0.08:
            alert_type = random.choice(['Over Speeding', 'Geofence Breach'])
            details = ""
            if alert_type == 'Over Speeding':
                details = f"Vehicle speed flagged at {new_speed} km/h (Limit: 60 km/h) on Outer Ring Road corridor."
            else:
                details = "Vehicle drifted off route corridor. Automated geo-fence alert generated."
                
            cursor.execute('''
                INSERT INTO safety_alerts (trip_id, alert_type, details, status, created_at)
                VALUES (?, ?, ?, 'Active', ?)
            ''', (trip["id"], alert_type, details, tick_time))
            alerts_added += 1
            
        # SOS trigger chance (5% chance)
        if new_status not in ['Completed', 'SOS Alert'] and random.random() < 0.05:
            cursor.execute('UPDATE trips SET status = "SOS Alert", speed = 0 WHERE id = ?', (trip["id"],))
            cursor.execute('''
                INSERT INTO safety_alerts (trip_id, alert_type, details, status, created_at)
                VALUES (?, 'SOS Panic', 'Passenger SOS Panic Button Triggered. Cabin audio link initiated.', 'Active', ?)
            ''', (trip["id"], tick_time))
            alerts_added += 1
            
    conn.commit()
    conn.close()
    return jsonify({"message": "Simulation tick complete.", "alerts_generated": alerts_added})


