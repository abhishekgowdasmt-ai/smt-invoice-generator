@app.route('/api/admin/trips', methods=['GET'])
def get_trips():
    if not check_admin_auth():
        return jsonify({"error": "Unauthorized Access"}), 401
    
    conn = get_db_connection()
    cursor = conn.cursor()
    
    # Fetch active trips
    cursor.execute('''
        SELECT t.*, c.reg_number as cab_reg, c.model as cab_model, c.fuel_type as cab_fuel, c.is_ev as cab_is_ev,
               d.name as driver_name, d.phone as driver_phone,
               co.name as company_name
        FROM trips t
        JOIN cabs c ON t.cab_id = c.id
        JOIN drivers d ON t.driver_id = d.id
        JOIN companies co ON t.company_id = co.id
        ORDER BY t.created_at DESC
    ''')
    rows = cursor.fetchall()
    
    trips = []
    for r in rows:
        trip_id = r["id"]
        # Fetch passengers
        cursor.execute('SELECT * FROM trip_passengers WHERE trip_id = ?', (trip_id,))
        pass_rows = cursor.fetchall()
        passengers = []
        for pr in pass_rows:
            passengers.append({
                "id": pr["id"],
                "name": pr["name"],
                "stop_name": pr["stop_name"],
                "status": pr["status"]
            })
        
        trips.append({
            "id": trip_id,
            "cab_id": r["cab_id"],
            "cab_reg": r["cab_reg"],
            "cab_model": r["cab_model"],
            "cab_fuel": r["cab_fuel"],
            "cab_is_ev": r["cab_is_ev"],
            "driver_id": r["driver_id"],
            "driver_name": r["driver_name"],
            "driver_phone": r["driver_phone"],
            "company_id": r["company_id"],
            "company_name": r["company_name"],
            "route_name": r["route_name"],
            "status": r["status"],
            "progress": r["progress"],
            "speed": r["speed"],
            "eta": r["eta"],
            "passengers": passengers,
            "created_at": r["created_at"]
        })
        
    conn.close()
    return jsonify(trips)


