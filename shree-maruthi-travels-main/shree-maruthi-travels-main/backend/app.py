def _proxy_to(target_base, subpath=''):
    url = target_base.rstrip('/') + '/' + subpath.lstrip('/')
    if request.query_string:
        url += '?' + request.query_string.decode('utf-8', 'ignore')
    hop = {'host', 'cookie', 'content-length', 'origin'}
    headers = {k: v for k, v in request.headers if k.lower() not in hop}
    try:
        import requests as http
        upstream = http.request(
            method=request.method,
            url=url,
            headers=headers,
            data=request.get_data(),
            allow_redirects=False,
            timeout=(5, 90),
        )
    except Exception:
        return None
    skip = {'content-encoding', 'content-length', 'transfer-encoding', 'connection'}
    out_headers = [(k, v) for k, v in upstream.headers.items() if k.lower() not in skip]
    return Response(upstream.content, upstream.status_code, out_headers)


