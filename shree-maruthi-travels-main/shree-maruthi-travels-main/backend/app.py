@app.route('/api/inquiries', methods=['POST'])
def create_inquiry():
    try:
        data = request.get_json()
        if not data:
            return jsonify({"error": "No input data provided"}), 400

        name = data.get('name')
        email = data.get('email')
        phone = data.get('phone')
        service_type = data.get('service_type')
        company = data.get('company', '')
        employee_count = data.get('employee_count', 0)
        details = data.get('details', '')

        if not all([name, email, phone, service_type]):
            return jsonify({"error": "Missing required fields (name, email, phone, service_type)"}), 400

        conn = get_db_connection()
        cursor = conn.cursor()
        created_at = datetime.now().strftime('%Y-%m-%d %H:%M:%S')

        cursor.execute('''
            INSERT INTO inquiries (name, email, phone, company, service_type, employee_count, details, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ''', (name, email, phone, company, service_type, employee_count, details, created_at))

        conn.commit()
        conn.close()

        # Build inquiry data dict for notifications
        inquiry_data = {
            "name": name,
            "company": company,
            "email": email,
            "phone": phone,
            "service_type": service_type,
            "employee_count": employee_count,
            "details": details
        }

        # Push to Zoho Sheet asynchronously
        if append_inquiry_to_sheet:
            threading.Thread(
                target=append_inquiry_to_sheet,
                args=(inquiry_data,)
            ).start()

        # Trigger email notification asynchronously
        threading.Thread(target=send_inquiry_email, args=(inquiry_data,)).start()

        return jsonify({"message": "Inquiry submitted successfully", "status": "success"}), 201
    except Exception as e:
        return jsonify({"error": str(e)}), 500


